/**
 * Translate dynamic rule-engine reasons & unverified criteria strings into Hindi
 */
export function translateCriteria(text, language = "en") {
  if (!text || typeof text !== "string") return text;
  if (language !== "hi") return text;

  // 1. Matches entity type: {type}
  let m = text.match(/^Matches entity type:\s*(.+)$/i);
  if (m) return `इकाई प्रकार से मेल खाता है: ${m[1]}`;

  // 2. Requires entity type {entities}, profile is '{profile}'.
  m = text.match(/^Requires entity type\s+(.+?),\s+profile is\s+'(.+?)'\.?$/i);
  if (m) return `इकाई प्रकार ${m[1]} आवश्यक है, प्रोफ़ाइल '${m[2]}' है।`;

  // 3. Matches gender requirement: {gender}
  m = text.match(/^Matches gender requirement:\s*(.+)$/i);
  if (m) {
    const g = m[1].toLowerCase() === "female" ? "महिला" : m[1].toLowerCase() === "male" ? "पुरुष" : m[1];
    return `लिंग आवश्यकता से मेल खाता है: ${g}`;
  }

  // 4. Requires gender '{gender}' — not provided in profile.
  m = text.match(/^Requires gender\s+'(.+?)'\s*—\s*not provided in profile\.?$/i);
  if (m) {
    const g = m[1].toLowerCase() === "female" ? "महिला" : m[1].toLowerCase() === "male" ? "पुरुष" : m[1];
    return `'${g}' लिंग आवश्यक है — प्रोफ़ाइल में नहीं दिया गया।`;
  }

  // 5. Matches age requirement ({min}-{max})
  m = text.match(/^Matches age requirement\s*\((.+?)\)$/i);
  if (m) return `आयु आवश्यकता से मेल खाता है (${m[1]} वर्ष)`;

  // 6. Requires age {min}-{max} — not provided in profile.
  m = text.match(/^Requires age\s+(.+?)\s*—\s*not provided in profile\.?$/i);
  if (m) return `आयु ${m[1]} वर्ष आवश्यक है — प्रोफ़ाइल में नहीं दी गई।`;

  // 7. Within income cap: ₹{cap}
  m = text.match(/^Within income cap:\s*(.+)$/i);
  if (m) return `आय सीमा के भीतर: ${m[1]}`;

  // 8. Requires income under ₹{cap} — not provided in profile.
  m = text.match(/^Requires income under\s*(.+?)\s*—\s*not provided in profile\.?$/i);
  if (m) return `${m[1]} से कम आय आवश्यक है — प्रोफ़ाइल में नहीं दी गई।`;

  // 9. Matches location: {state}
  m = text.match(/^Matches location:\s*(.+)$/i);
  if (m) {
    const stateHi = STATE_TRANSLATIONS[m[1]]?.hi || m[1];
    return `स्थान से मेल खाता है: ${stateHi}`;
  }

  // 10. Restricted to {states} — state not provided in profile.
  m = text.match(/^Restricted to\s+(.+?)\s*—\s*state not provided in profile\.?$/i);
  if (m) return `${m[1]} तक सीमित — प्रोफ़ाइल में राज्य नहीं दिया गया।`;

  // 11. Matches business stage: {stage}
  m = text.match(/^Matches business stage:\s*(.+)$/i);
  if (m) {
    const st = m[1] === "new" ? "नया (New)" : m[1] === "existing" ? "मौजूदा (Existing)" : m[1];
    return `व्यवसाय चरण से मेल खाता है: ${st}`;
  }

  // 12. Requires business stage '{stage}' — not provided in profile.
  m = text.match(/^Requires business stage\s+'(.+?)'\s*—\s*not provided in profile\.?$/i);
  if (m) {
    const st = m[1] === "new" ? "नया (New)" : m[1] === "existing" ? "मौजूदा (Existing)" : m[1];
    return `व्यवसाय चरण '${st}' आवश्यक है — प्रोफ़ाइल में नहीं दिया गया।`;
  }

  // 13. Matches sector: {sector}
  m = text.match(/^Matches sector:\s*(.+)$/i);
  if (m) {
    const secHi = SECTOR_TRANSLATIONS[m[1]]?.hi || m[1];
    return `कार्यक्षेत्र से मेल खाता है: ${secHi}`;
  }

  // 14. Restricted to sectors {sectors} — sector not provided in profile.
  m = text.match(/^Restricted to sectors\s+(.+?)\s*—\s*sector not provided in profile\.?$/i);
  if (m) return `कार्यक्षेत्र ${m[1]} तक सीमित — प्रोफ़ाइल में क्षेत्र नहीं दिया गया।`;

  // 15. No restrictive criteria found — broadly eligible.
  if (text.includes("No restrictive criteria found")) {
    return "कोई प्रतिबंधात्मक शर्त नहीं — व्यापक रूप से पात्र।";
  }

  return text;
}
